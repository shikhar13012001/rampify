#!/usr/bin/env node
/**
 * Reads owner-provided exports from validation-data/ (gitignored — see
 * validation-data/README.md for expected file names/formats) and writes
 * docs/validation/WEEKLY_REPORT.md. Pure computation lives in
 * scripts/lib/reportMetrics.mjs (tested with synthetic fixtures in
 * test/reporting/reportMetrics.test.ts); this file is I/O + Markdown
 * rendering only.
 *
 * Usage:
 *   node scripts/generate-weekly-report.mjs [--since YYYY-MM-DD] [--until YYYY-MM-DD]
 *
 * Defaults to the last 7 complete UTC calendar days if omitted. Missing
 * input files are handled honestly — sections report "no data available"
 * rather than being filled with anything invented. Never run this against
 * real data without first regenerating it via
 * scripts/export-analytics-events.mjs for the same window.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import {
  isQualifiedEvent,
  computeFunnelByAcquisition,
  computePaymentTotals,
  toMillis,
  parseCsv,
  normalizeGscRow,
  summarizeGscRows,
  splitBranded,
} from './lib/reportMetrics.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const dataDir = join(root, 'validation-data');
const outPath = join(root, 'docs', 'validation', 'WEEKLY_REPORT.md');

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--since') args.since = argv[++i];
    if (argv[i] === '--until') args.until = argv[++i];
  }
  return args;
}

function defaultRange() {
  const until = new Date();
  until.setUTCHours(0, 0, 0, 0);
  const since = new Date(until);
  since.setUTCDate(since.getUTCDate() - 7);
  const fmt = (d) => d.toISOString().slice(0, 10);
  return { since: fmt(since), until: fmt(until) };
}

function readJsonIfExists(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, 'utf-8'));
  } catch (err) {
    console.error(`Failed to parse ${path}:`, err.message);
    return null;
  }
}

function readCsvIfExists(path) {
  if (!existsSync(path)) return null;
  try {
    return parseCsv(readFileSync(path, 'utf-8'));
  } catch (err) {
    console.error(`Failed to parse ${path}:`, err.message);
    return null;
  }
}

function pct(n, total) {
  if (!total) return '—';
  return `${((n / total) * 100).toFixed(1)}%`;
}

function fmtMs(ms) {
  if (ms === null || ms === undefined) return '—';
  const s = ms / 1000;
  if (s < 60) return `${s.toFixed(0)}s`;
  const m = s / 60;
  if (m < 60) return `${m.toFixed(1)}m`;
  return `${(m / 60).toFixed(1)}h`;
}

// ─── Load inputs ────────────────────────────────────────────────────────────

const args = parseArgs(process.argv.slice(2));
const { since, until } = { ...defaultRange(), ...args };
const sinceMs = new Date(`${since}T00:00:00.000Z`).getTime();
const untilExclusiveMs = new Date(`${until}T00:00:00.000Z`).getTime() + 24 * 60 * 60 * 1000;

const allEvents = readJsonIfExists(join(dataDir, 'analytics-events.json'));
const gscQueryRows = readCsvIfExists(join(dataDir, 'search-console-queries.csv'));
const gscPageRows = readCsvIfExists(join(dataDir, 'search-console-pages.csv'));
const gscTotalsRows = readCsvIfExists(join(dataDir, 'search-console-totals.csv'));
const experimentLogRows = readCsvIfExists(join(dataDir, 'experiment-log.csv'));

const windowedEvents = Array.isArray(allEvents)
  ? allEvents.filter((e) => {
      const ms = toMillis(e.timestamp);
      return ms !== null && ms >= sinceMs && ms < untilExclusiveMs;
    })
  : null;

// ─── Analytics section ──────────────────────────────────────────────────────

const lines = [];
lines.push('# Rampcut — Weekly Report');
lines.push('');
lines.push(`> Companion to \`STATUS.md\` / \`WORKING_AGREEMENT.md\` / \`METRICS.md\`. Generated by`);
lines.push('> `scripts/generate-weekly-report.mjs` — regenerate after refreshing');
lines.push('> `validation-data/` (see `validation-data/README.md`), don\'t hand-edit.');
lines.push('');
lines.push(`**Window**: ${since} to ${until} (inclusive, UTC). Generated: ${new Date().toISOString()}.`);
lines.push('');

if (!Array.isArray(allEvents)) {
  lines.push('## No analytics data available for this period');
  lines.push('');
  lines.push(
    '`validation-data/analytics-events.json` does not exist. Nothing below is fabricated ' +
      'to fill this gap, per `WORKING_AGREEMENT.md` §6 — run:',
  );
  lines.push('');
  lines.push('```');
  lines.push(`node --env-file=.env.local scripts/export-analytics-events.mjs --since ${since} --until ${until}`);
  lines.push('node scripts/generate-weekly-report.mjs --since ' + since + ' --until ' + until);
  lines.push('```');
  lines.push('');
  lines.push('then re-run this script. See `validation-data/README.md` for the exact expected files.');
  lines.push('');
} else {
  const totalRaw = allEvents.length;
  const inWindow = windowedEvents.length;
  const testInWindow = windowedEvents.filter((e) => !isQualifiedEvent(e)).length;

  const { groups, droppedEventCount, dropped } = computeFunnelByAcquisition(windowedEvents);
  const payments = computePaymentTotals(windowedEvents);

  lines.push(
    `${totalRaw} total events exported; ${inWindow} fall inside the ${since}–${until} window ` +
      `(${testInWindow} of those are \`isTestSession\` and excluded from every count below).`,
  );
  if (droppedEventCount > 0) {
    const reasons = {};
    for (const d of dropped) reasons[d.reason] = (reasons[d.reason] ?? 0) + 1;
    lines.push('');
    lines.push(
      `**${droppedEventCount} event(s) dropped from grouping** (not counted anywhere below): ` +
        Object.entries(reasons).map(([r, n]) => `${n} (${r})`).join(', ') +
        ' — see "Missing identity, consent, and deduplication limitations" below.',
    );
  }
  lines.push('');

  const totalQualified = groups.reduce((s, g) => s + g.qualifiedVisitors, 0);

  lines.push('## By acquisition source and landing page');
  lines.push('');
  if (groups.length === 0) {
    lines.push('No qualified (non-test) sessions in this window.');
  } else {
    lines.push(
      '| Source | Landing page | Qualified visitors | Editor starts | Own clip loads | Demo clip loads | Activated (first) | Export started | Export completed | Export validated | Export failed | Export cancelled | Downloads | Signups | Checkout started |',
    );
    lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
    for (const g of groups) {
      lines.push(
        `| ${g.source} | ${g.landingPath} | ${g.qualifiedVisitors} (${pct(g.qualifiedVisitors, totalQualified)}) ` +
          `| ${g.editorStarts} (${pct(g.editorStarts, g.qualifiedVisitors)}) ` +
          `| ${g.clipLoadedOwn} | ${g.clipLoadedDemo} ` +
          `| ${g.activatedSessions} (${pct(g.activatedSessions, g.qualifiedVisitors)}) ` +
          `| ${g.exportStarted} | ${g.exportCompleted} | ${g.exportValidated} ` +
          `| ${g.exportFailed} | ${g.exportCancelled} | ${g.downloadInitiated} ` +
          `| ${g.signups} | ${g.checkoutStarted} |`,
      );
    }
    lines.push('');
    lines.push('Percentages: qualified-visitor share is of the total across all groups; every other');
    lines.push('percentage in this table is of that row\'s own qualified-visitor count (its own funnel).');
    lines.push('');
    lines.push('### Time to first activation, and failure stages, per group');
    lines.push('');
    lines.push('| Source | Landing page | Median time to first activation | Failure stages (count) |');
    lines.push('|---|---|---|---|');
    for (const g of groups) {
      const stages = Object.entries(g.failureStages).map(([s, n]) => `${s}: ${n}`).join(', ') || '—';
      lines.push(`| ${g.source} | ${g.landingPath} | ${fmtMs(g.medianTimeToActivationMs)} | ${stages} |`);
    }
  }
  lines.push('');

  lines.push('## Verified paying customers (not attributable to acquisition source)');
  lines.push('');
  lines.push(`**${payments.verifiedPayingCustomers}** distinct users with a server-verified first payment in this window.`);
  lines.push('');
  lines.push(`> ${payments.note}`);
  lines.push('');

  // ─── Cash spend / founder effort ──────────────────────────────────────────
  lines.push('## Cash spend and founder effort');
  lines.push('');
  if (Array.isArray(experimentLogRows) && experimentLogRows.length > 0) {
    lines.push('From `validation-data/experiment-log.csv` (see `docs/validation/LAUNCH.md` §6 for the source format):');
    lines.push('');
    lines.push('| Date | Audience | Source / Channel | Spend | Result |');
    lines.push('|---|---|---|---|---|');
    for (const row of experimentLogRows) {
      lines.push(
        `| ${row.Date ?? row.date ?? '—'} | ${row.Audience ?? row.audience ?? '—'} | ` +
          `${row['Source / Channel'] ?? row.Source ?? '—'} | ${row.Spend ?? row.spend ?? '—'} | ${row.Result ?? row.result ?? '—'} |`,
      );
    }
  } else {
    lines.push('Not supplied for this period — `validation-data/experiment-log.csv` was not found.');
    lines.push('Reported as unknown, not zero: no spend/effort data existing is different from confirmed $0 spend.');
  }
  lines.push('');

  lines.push('## Missing identity, consent, and deduplication limitations');
  lines.push('');
  lines.push('Restated from `docs/validation/METRICS.md` — these are structural, not fixed by this report:');
  lines.push('');
  lines.push('- **No cross-device/cross-browser identity**: `anonId` is per-browser (localStorage); the same');
  lines.push('  real visitor on two devices counts as two qualified visitors until they sign in on both.');
  lines.push('- **`payment_succeeded` has no session/acquisition data at all** — verified paying customers');
  lines.push('  above cannot be joined to the acquisition table, by design of the webhook having no browser context.');
  lines.push('- **Consent is opt-out (Do Not Track), not an opt-in banner** — no consent-banner UI exists yet,');
  lines.push('  so visitors with DNT unset are counted; this is a disclosed gap, not a bug in this report.');
  lines.push('- **Dedup is send-scoped, not delivery-guaranteed** — a `trackEvent()` call whose `fetch` failed');
  lines.push('  outright (offline, blocked) is simply missing from this data, not retried or backfilled.');
  if (droppedEventCount > 0) {
    lines.push(`- **This run**: ${droppedEventCount} exported event(s) had no sessionId or an unparseable`);
    lines.push('  timestamp and were excluded from every count above rather than guessed into a group.');
  }
  lines.push('');
}

// ─── Search Console section ─────────────────────────────────────────────────

lines.push('## Search Console');
lines.push('');

const daysAgo = (dateStr) => (Date.now() - new Date(`${dateStr}T00:00:00.000Z`).getTime()) / 86_400_000;
if (daysAgo(until) < 3) {
  lines.push(
    `**Window caution**: Search Console data typically lags 1-3 days. The requested window ends ${until} ` +
      `(${daysAgo(until).toFixed(1)} days ago) — treat this window as potentially incomplete, not a` +
      ' final number, until re-checked after it fully ages.',
  );
  lines.push('');
}

if (!gscQueryRows && !gscPageRows && !gscTotalsRows) {
  lines.push(
    'No Search Console export found (`validation-data/search-console-queries.csv` / `-pages.csv` / ' +
      '`-totals.csv`). See `validation-data/README.md` for how to produce these from the Search Console UI.',
  );
  lines.push('');
} else {
  if (gscTotalsRows) {
    const totalsNormalized = gscTotalsRows.map((r) => normalizeGscRow(r, 'Date'));
    const totals = summarizeGscRows(totalsNormalized);
    lines.push('### Property totals (unfiltered)');
    lines.push('');
    lines.push(`Clicks: ${totals.totalClicks} · Impressions: ${totals.totalImpressions} · CTR: ${totals.ctr !== null ? (totals.ctr * 100).toFixed(2) + '%' : '—'} (from summed clicks/impressions, not an average of daily CTRs).`);
    lines.push('');
  }

  if (gscQueryRows) {
    const normalized = gscQueryRows.map((r) => normalizeGscRow(r, 'Query'));
    const { branded, nonBranded } = splitBranded(normalized);
    const brandedSummary = summarizeGscRows(branded);
    const nonBrandedSummary = summarizeGscRows(nonBranded);
    lines.push('### Queries — branded vs. non-branded');
    lines.push('');
    lines.push('| | Rows | Clicks | Impressions | CTR |');
    lines.push('|---|---|---|---|---|');
    lines.push(`| Branded ("rampcut") | ${brandedSummary.rowCount} | ${brandedSummary.totalClicks} | ${brandedSummary.totalImpressions} | ${brandedSummary.ctr !== null ? (brandedSummary.ctr * 100).toFixed(2) + '%' : '—'} |`);
    lines.push(`| Non-branded | ${nonBrandedSummary.rowCount} | ${nonBrandedSummary.totalClicks} | ${nonBrandedSummary.totalImpressions} | ${nonBrandedSummary.ctr !== null ? (nonBrandedSummary.ctr * 100).toFixed(2) + '%' : '—'} |`);
    lines.push('');
    lines.push(
      `This export is capped at (up to) 1,000 rows by Google's own UI export, and Search Console additionally ` +
        `omits some very-low-volume queries entirely regardless of the cap — **${normalized.length} row(s) shown ` +
        'here is not necessarily every query that got an impression; treat as a lower bound, and do not assume it' +
        ' equals any property-level total shown above.**',
    );
    lines.push('');
    lines.push('CTR figures above are computed from summed clicks/impressions across all rows in each group —');
    lines.push('never from averaging each query\'s own reported CTR (which would over-weight low-impression rows).');
    lines.push('Per-query position is available in the raw export for individual queries only — no single');
    lines.push('aggregate "average position" number is computed or shown here, since that figure would not');
    lines.push('represent any individual query\'s actual rank.');
    lines.push('');
  }

  if (gscPageRows) {
    const normalized = gscPageRows.map((r) => normalizeGscRow(r, 'Page'));
    const summary = summarizeGscRows(normalized);
    lines.push('### Pages');
    lines.push('');
    lines.push(`${summary.rowCount} page(s) — Clicks: ${summary.totalClicks} · Impressions: ${summary.totalImpressions} · CTR: ${summary.ctr !== null ? (summary.ctr * 100).toFixed(2) + '%' : '—'} (summed, not averaged).`);
    lines.push('');
  }
}

// ─── Recommendation ─────────────────────────────────────────────────────────

lines.push('## Recommendation — which source or funnel stage deserves the next experiment?');
lines.push('');

if (!Array.isArray(allEvents) || computeFunnelByAcquisition(windowedEvents ?? []).groups.length === 0) {
  lines.push(
    '**No recommendation — insufficient data.** There is no qualified-session data for this window to rank ' +
      'sources or funnel stages against each other. Run `scripts/export-analytics-events.mjs` after real traffic ' +
      'exists, then re-generate this report, before asking this question again.',
  );
} else {
  const { groups } = computeFunnelByAcquisition(windowedEvents);
  const withVisitors = groups.filter((g) => g.qualifiedVisitors >= 3); // avoid ranking a 1-visitor group
  if (withVisitors.length === 0) {
    lines.push(
      '**No recommendation — every group has too few qualified visitors (<3) to compare meaningfully.** ' +
        'Gather more traffic per source before ranking.',
    );
  } else {
    const bySize = [...withVisitors].sort((a, b) => b.qualifiedVisitors - a.qualifiedVisitors)[0];
    const activationRate = (g) => (g.qualifiedVisitors > 0 ? g.activatedSessions / g.qualifiedVisitors : 0);
    const worstActivation = [...withVisitors].sort((a, b) => activationRate(a) - activationRate(b))[0];
    lines.push(
      `Largest qualified-visitor source this window: **${bySize.source} → ${bySize.landingPath}** ` +
        `(${bySize.qualifiedVisitors} visitors, ${pct(bySize.activatedSessions, bySize.qualifiedVisitors)} activation).`,
    );
    lines.push('');
    lines.push(
      `Lowest activation rate among groups with enough volume to judge: **${worstActivation.source} → ` +
        `${worstActivation.landingPath}** (${pct(worstActivation.activatedSessions, worstActivation.qualifiedVisitors)}` +
        ' activation) — this is the more useful place to run the next experiment than the biggest source, since',
    );
    lines.push('improving a low-activation source with real volume has more headroom than optimizing an already-working one.');
  }
}
lines.push('');
lines.push('This recommendation is a heuristic (largest-volume vs. lowest-activation-rate-with-minimum-volume),');
lines.push('not a statistical significance test — treat it as a starting hypothesis for the experiment log');
lines.push('in `docs/validation/LAUNCH.md` §6, not a conclusion.');
lines.push('');

writeFileSync(outPath, lines.join('\n') + '\n', 'utf-8');
console.log(`Wrote ${outPath}`);
